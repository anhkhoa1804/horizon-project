/**
 * Threshold types and pure helpers — NO database, NO `server-only`.
 *
 * Split out from `thresholds.ts` because the public registry table is a client
 * component: it renders bands and needs `formatBand`. Importing that from a
 * module marked `server-only` fails the build, and the fix is not to drop the
 * marker (the loaders genuinely must not reach the browser — they hold a
 * service-role client) but to separate the pure half.
 *
 * Nothing here touches Supabase. Everything here is safe on either side.
 */


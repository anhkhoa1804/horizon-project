/**
 * The thresholds that may actually colour something, for one quantity.
 *
 * Matches on QUANTITY, not metric_key — the whole point of the distinction.
 * Returns only active rows, so a caller cannot accidentally evaluate a
 * reference figure by forgetting to filter.
 */
export function activeThresholdsFor(rows: ThresholdRow[], quantity: string): ThresholdRow[] {
  return rows.filter((r) => r.quantity === quantity && r.is_active);
}

/**
 * The severity a value earns, or null for "no opinion".
 *
 * Returning null is the common case and the correct one for most metrics in
 * this system. It means no ACTIVE threshold covers this quantity — not that
 * the reading is fine.
 */
export function resolveSeverity(
  rows: ThresholdRow[],
  quantity: string,
  value: number | null,
): { severity: ThresholdSeverity; row: ThresholdRow } | null {
  if (value === null || !Number.isFinite(value)) return null;

  const RANK: Record<ThresholdSeverity, number> = {
    normal: 0,
    low_confidence: 1,
    watch: 2,
    warning: 3,
    critical: 4,
  };

  let worst: { severity: ThresholdSeverity; row: ThresholdRow } | null = null;

  for (const row of activeThresholdsFor(rows, quantity)) {
    const lower = row.threshold_value;
    const upper = row.upper_value;
    if (lower === null) continue;

    let hit = false;
    switch (row.comparison) {
      case "above":
        hit = value > lower;
        break;
      case "below":
        hit = value < lower;
        break;
      case "between":
        hit = upper !== null && value >= lower && value <= upper;
        break;
      case "outside":
        hit = upper !== null && (value < lower || value > upper);
        break;
    }

    if (hit && (!worst || RANK[row.severity] > RANK[worst.severity])) {
      worst = { severity: row.severity, row };
    }
  }

  return worst;
}

/**
 * A public, informational reading of sourced rows that are deliberately not
 * active operational thresholds. This never creates an alert or action; it
 * merely lets Monitoring say where a compatible measurement sits relative to
 * a published reference or pilot band.
 */
export function resolveReferenceSeverity(
  rows: ThresholdRow[],
  quantity: string,
  value: number | null,
): { severity: ThresholdSeverity; row: ThresholdRow } | null {
  if (value === null || !Number.isFinite(value)) return null;

  const RANK: Record<ThresholdSeverity, number> = {
    normal: 0,
    low_confidence: 1,
    watch: 2,
    warning: 3,
    critical: 4,
  };
  let worst: { severity: ThresholdSeverity; row: ThresholdRow } | null = null;

  for (const row of rows) {
    if (row.quantity !== quantity || row.is_active || row.threshold_value === null) continue;
    const lower = row.threshold_value;
    const upper = row.upper_value;
    const hit = row.comparison === "above"
      ? value > lower
      : row.comparison === "below"
        ? value < lower
        : row.comparison === "between"
          ? upper !== null && value >= lower && value <= upper
          : upper !== null && (value < lower || value > upper);
    if (hit && (!worst || RANK[row.severity] > RANK[worst.severity])) worst = { severity: row.severity, row };
  }
  return worst;
}

/**
 * A row's band as a reader reads it.
 *
 * Deliberately SYMBOLIC and language-free — `<`, `>`, an en-dash range, and
 * `∉` for "outside". Display text belongs in lib/i18n; a band is notation, and
 * notation does not need translating. The alternative was a Vietnamese word in
 * a lib module, which is exactly what the i18n guard exists to catch.
 */
export function formatBand(row: ThresholdRow): string {
  const v = row.threshold_value;
  const u = row.upper_value;
  const unit = row.unit === "pH" ? "" : ` ${row.unit}`;
  switch (row.comparison) {
    case "above":
      return `> ${v}${unit}`;
    case "below":
      return `< ${v}${unit}`;
    case "between":
      return `${v} – ${u}${unit}`;
    case "outside":
      return `∉ ${v} – ${u}${unit}`;
  }
}

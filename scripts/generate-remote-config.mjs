import fs from "node:fs";
const s=JSON.parse(fs.readFileSync(new URL("../contracts/remote-config.v1.schema.json",import.meta.url)));
const p=s.properties,w=s["x-wire"];
const h=`// Generated by scripts/generate-remote-config.mjs; do not edit.
#pragma once
#include <stdint.h>
#include <stddef.h>
namespace horizon {
constexpr uint32_t CONFIG_VERSION=${p.contract_version.const};
constexpr uint32_t MAX_REVISION=${p.config_revision.maximum}UL;
constexpr uint32_t SAMPLE_MIN=${p.sample_interval_seconds.minimum}, INTERVAL_MAX=${p.sample_interval_seconds.maximum};
constexpr size_t CONFIG_FRAME_MAX=${w.max_frame_bytes};
constexpr const char* CONFIG_MODES[]={${p.mode.enum.map(v=>JSON.stringify(v)).join(",")}};
constexpr const char* CONFIG_TYPES[]={${w.types.map(v=>JSON.stringify(v)).join(",")}};
constexpr const char* CONFIG_REASONS[]={${w.reasons.map(v=>JSON.stringify(v)).join(",")}};
}
`;
const target=new URL("../firmware/esp32-node/src/shared/config_contract.generated.h",import.meta.url);
fs.mkdirSync(new URL("../firmware/esp32-node/src/shared/",import.meta.url),{recursive:true});
if(process.argv.includes("--check")){if(fs.readFileSync(target,"utf8")!==h)throw Error("Generated config contract drift");}else fs.writeFileSync(target,h);
